mkdirSync(join(out, "fx"), { recursive: true });
let gd = "extends RefCounted\n## Generated by tools/build_fx.mjs from the pixelfx library. Do not edit by hand.\n## name: [fps, loop, frames, frame_w, frame_h, pivot_x, pivot_y, columns, fade_out]\n\nconst DATA := {\n";
let total = 0;
for (const [alias, id, fps, options, cut] of LIST) {
  const fx = await loadEffect(id);
  const r = renderFrames(fx, { fps, options: options ?? undefined, actor: false });
  let frames = r.frames;
  if (cut) frames = frames.slice(0, Math.round(cut * r.fps));
  // crop every frame to the box the effect actually uses (screen transitions stay full size)
  let x0 = r.w, y0 = r.h, x1 = -1, y1 = -1;
  for (const f of frames) for (let y = 0; y < r.h; y++) for (let x = 0; x < r.w; x++) if (f.clear[(y * r.w + x) * 4 + 3]) {
    if (x < x0) x0 = x;
    if (x > x1) x1 = x;
    if (y < y0) y0 = y;
    if (y > y1) y1 = y;
  }
  if (alias.startsWith("t_") || x1 < 0) { x0 = 0; y0 = 0; x1 = r.w - 1; y1 = r.h - 1; }
  const cw = x1 - x0 + 1, ch = y1 - y0 + 1;
  frames = frames.map((f) => {
    const c = new Uint8ClampedArray(cw * ch * 4);
    for (let y = 0; y < ch; y++) c.set(f.clear.subarray(((y + y0) * r.w + x0) * 4, ((y + y0) * r.w + x0 + cw) * 4), y * cw * 4);
    return { clear: c };
  });
  const s = spriteSheet(fx, { w: cw, h: ch, frames, fps: r.fps }, alias);
  const m = s.json.meta.pixelfx;
  const pivot = [m.pivot[0] - x0, m.pivot[1] - y0];
  if (!only || only === alias) save(join(out, "fx", `${alias}.png`), s.png);
  const sz = s.json.meta.size;
  total += sz.w * sz.h;
  if (sz.w > 4096 || sz.h > 4096) console.error(`TOO BIG ${alias} ${sz.w}x${sz.h}`);
  gd += `\t"${alias}": [${m.fps}, ${m.loop}, ${m.frames}, ${cw}, ${ch}, ${pivot[0]}, ${pivot[1]}, ${m.columns}, ${cut ? 1 : 0}],\n`;
  console.log(alias.padEnd(16), `${m.frames}f`, `${cw}x${ch}`, `sheet ${sz.w}x${sz.h}`, "pivot", pivot.join(","));
}
gd += "}\n";
writeFileSync(join(out, "fx_data.gd"), gd);
console.log("total megapixels", (total / 1e6).toFixed(1), "=> VRAM MB", (total * 4 / 1048576).toFixed(0));
